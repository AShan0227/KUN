def _task_plan_for(
    control_plane: InMemoryControlPlane,
    mission: Mission,
    task_plan_version: str,
) -> TaskPlan:
    for plan in control_plane.task_plans.values():
        if plan.mission_id == mission.mission_id and plan.version == task_plan_version:
            return plan
    raise ValueError(f"task plan version not found: {task_plan_version}")


def _spec_from_contract(contract: ExecutionContract) -> GameProductionSpec:
    project_path = contract.delivery_contract.get("project_path")
    if not isinstance(project_path, str) or not project_path.strip():
        raise ValueError("delivery_contract.project_path is required")
    production_mode = contract.delivery_contract.get("production_mode")
    if not isinstance(production_mode, str) or not production_mode.strip():
        raise ValueError(
            "delivery_contract.production_mode is required to prevent historical task "
            "template leakage into new missions"
        )
    production_mode = production_mode.strip()
    if production_mode not in SUPPORTED_GAME_PRODUCTION_MODES:
        raise ValueError(
            "unsupported delivery_contract.production_mode: "
            f"{production_mode!r}; supported modes are {sorted(SUPPORTED_GAME_PRODUCTION_MODES)}"
        )
    app_name = contract.delivery_contract.get("app_name", "KUN Game Project")
    if not isinstance(app_name, str) or not app_name.strip():
        app_name = "KUN Game Project"
    final_player_experience_required = bool(
        contract.delivery_contract.get(
            "final_player_experience_required",
            "final_standard" in contract.delivery_contract,
        )
    )
    required_test_scripts = contract.delivery_contract.get("required_test_scripts", [])
    if isinstance(required_test_scripts, str):
        required_test_scripts = [required_test_scripts]
    if not isinstance(required_test_scripts, list):
        required_test_scripts = []
    local_dev_port = contract.delivery_contract.get(
        "local_dev_port", contract.delivery_contract.get("port", 5178)
    )
    try:
        local_dev_port = int(local_dev_port)
    except (TypeError, ValueError):
        local_dev_port = 5178
    return GameProductionSpec(
        project_path=Path(project_path).expanduser().resolve(),
        app_name=app_name.strip(),
        production_mode=production_mode,
        benchmark_residual_required=bool(
            contract.delivery_contract.get("benchmark_residual_required", False)
        ),
        benchmark_residual_threshold=float(
            contract.delivery_contract.get("benchmark_residual_threshold", 0.18)
        ),
        user_accepts_residual=bool(contract.delivery_contract.get("user_accepts_residual", False)),
        final_player_experience_required=final_player_experience_required,
        final_player_experience_threshold=float(
            contract.delivery_contract.get("final_player_experience_threshold", 0.95)
        ),
        visual_product_iteration_required=bool(
            contract.delivery_contract.get("visual_product_iteration_required", False)
        ),
        required_test_scripts=[str(item) for item in required_test_scripts if str(item).strip()],
        local_dev_port=local_dev_port,
    )


