def _causal_physics_ts() -> str:
    return """import type { GeneratedObject } from "../types";

type CausalOutcome = {
  mass: "light" | "medium" | "heavy";
  motion: "static" | "rolling" | "floating" | "flying" | "bouncy";
  affordanceGraph: string[];
  facts: string[];
  summary: string;
};

function has(object: GeneratedObject, property: string): boolean {
  return object.properties.includes(property) || object.ruleFamilies.includes(property);
}

export function explainCausalOutcome(object: GeneratedObject, activeTags: string[] = []): CausalOutcome {
  const mass = has(object, "heavy") || has(object, "stone") || has(object, "metal")
    ? "heavy"
    : has(object, "lightweight") || has(object, "floating") || has(object, "flying")
      ? "light"
      : "medium";
  const motion = has(object, "flying")
    ? "flying"
    : has(object, "floating")
      ? "floating"
      : has(object, "bouncy")
        ? "bouncy"
        : object.ruleFamilies.includes("movement")
          ? "rolling"
          : "static";
  const affordanceGraph = [
    object.ruleFamilies.includes("crossing") || motion === "flying" || motion === "floating" ? "route" : "",
    object.ruleFamilies.includes("light") || has(object, "illuminating") ? "visibility" : "",
    object.ruleFamilies.includes("comfort") || has(object, "friendly") ? "npc-trust" : "",
    object.action === "combine" || object.action === "attach" ? "compound-tool" : "",
    activeTags.includes("unlocking") && object.ruleFamilies.includes("repair") ? "repair-chain" : "",
  ].filter(Boolean);
  const facts = [
    `重量:${mass}`,
    `运动:${motion}`,
    affordanceGraph.length ? `作用:${affordanceGraph.join("/")}` : "作用:观察/占位",
  ];
  return {
    mass,
    motion,
    affordanceGraph,
    facts,
    summary: `因果反馈：${object.name} 的${facts.join("，")}，可以继续用属性或组合改变解法。`,
  };
}
"""


